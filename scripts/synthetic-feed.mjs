// Synthetic list pages for the infinite-scroll checks, built from the captured news pages. They stand in for
// states the capture lacks: a front page that shifted while the reader scrolled, HN's throttle page, and pages
// three and beyond.
//
//   node scripts/synthetic-feed.mjs    writes fixtures/synthetic/news-p2-shifted.html and rate-limited.html

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = resolve(import.meta.dirname, '..');
const read = (name) => readFileSync(join(ROOT, 'fixtures', name), 'utf8');

/** A list page split around its story rows: each block is the title row, the subtext row and the spacer. */
const split = (html) => {
  const start = html.indexOf('<tr class="athing submission"');
  const end = html.indexOf('<tr class="morespace"');
  const blocks = html.slice(start, end).split(/(?=<tr class="athing submission")/);
  return { head: html.slice(0, start), blocks, tail: html.slice(end) };
};

const setRank = (block, rank) => block.replace(/class="rank">\d+\./, `class="rank">${rank}.`);

/**
 * news?p=2 after three stories dropped off the front page: page two now starts with the last three stories of
 * page one (ranks 31-33), and its own stories move down three places.
 */
export const shiftedNewsP2 = () => {
  const one = split(read('news.html'));
  const two = split(read('news-p2.html'));
  const fallen = one.blocks.slice(-3).map((b, i) => setRank(b, 31 + i).replaceAll('goto=news"', 'goto=news%3Fp%3D2"').replaceAll("goto=news'", "goto=news%3Fp%3D2'"));
  const moved = two.blocks.slice(0, -3).map((b, i) => setRank(b, 34 + i));
  return `<!-- SYNTHETIC: generated by scripts/synthetic-feed.mjs from news.html and news-p2.html -->\n${two.head}${[...fallen, ...moved].join('')}${two.tail}`;
};

/** HN's throttle answer: one sentence, no page frame. */
export const rateLimited = () =>
  `<html><head><!-- SYNTHETIC: HN's throttle page, written by scripts/synthetic-feed.mjs --></head><body>Sorry, we're not able to serve your requests this quickly.</body></html>\n`;

/**
 * news?p=N for N >= 3: page two with every story id moved out of the real range, ranks continued and the More
 * link pointing at N + 1, so a scroll can keep loading past what the capture holds.
 */
export const syntheticNewsPage = (n) => {
  let html = read('news-p2.html');
  const ids = [...html.matchAll(/<tr class="athing submission" id="(\d+)"/g)].map((m) => m[1]);
  for (const id of ids) html = html.replaceAll(id, String(Number(id) + (n - 2) * 100_000_000));
  html = html.replace(/class="rank">(\d+)\./g, (_, r) => `class="rank">${Number(r) + (n - 2) * 30}.`);
  html = html.replaceAll('goto=news%3Fp%3D2', `goto=news%3Fp%3D${n}`).replace(/href='\?p=3'/, `href='?p=${n + 1}'`);
  return `<!-- SYNTHETIC: news?p=${n} generated by scripts/synthetic-feed.mjs from news-p2.html -->\n${html}`;
};

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(join(ROOT, 'fixtures', 'synthetic', 'news-p2-shifted.html'), shiftedNewsP2());
  writeFileSync(join(ROOT, 'fixtures', 'synthetic', 'rate-limited.html'), rateLimited());
}
